/**
 * Повертає текст підказки для продукту або null, якщо підказки немає.
 *
 * @param {string} productTitle Точна назва продукту з БД (Product.title).
 * @returns {string|null}
 */
export function getProductWeightHint(productTitle) {
  if (typeof productTitle !== 'string') return null;
  const key = productTitle.trim();
  if (!key) return null;
  return PRODUCT_WEIGHT_HINTS[key] ?? null;
}

